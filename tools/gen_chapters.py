"""Build notes/CHAPTERS.md (every Ardan chapter, tagged with its roadmap stage) from CURRICULUM.md.

Usage: python tools/gen_chapters.py [path-to-CURRICULUM.md]
Default source: D:/RustroverProjects/Rust_vedio/library/CURRICULUM.md
"""
import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else r"D:/RustroverProjects/Rust_vedio/library/CURRICULUM.md")
OUT = Path(__file__).resolve().parent.parent / "notes" / "CHAPTERS.md"

STAGES = [
    ("S1", "The machine in memory", "Part 1 Crash Course (rest)"),
    ("S2", "Operator console", "Part 2 §1 Getting Started"),
    ("S3", "Shop-floor quality", "Part 5 §1-2 + Part 4 Best Practices"),
    ("S4", "Digital twin", "Part 5 §3-6 Rusty Engine"),
    ("S5", "The servo thread", "Part 2 §2 Threads"),
    ("S6", "The machine on the network", "Part 2 §3 Async"),
    ("S7", "Bits on the wire", "Part 2 §4-6 + Part 3"),
    ("S8", "The machine as a service", "Part 6 Rust as a Service"),
    ("S9", "Graduation", "Part 7 Webinars"),
]


def stage(p, s, i):
    if p == 0:
        return "S1" if s == 0 else None  # 0.1.x are our own pages, not Ardan items
    if p == 1:
        return "S1"
    if p == 2:
        return {0: "S2", 1: "S2", 2: "S5", 3: "S6"}.get(s, "S7")
    if p == 3:
        return "S7"
    if p == 4:
        return "S3"
    if p == 5:
        return "S3" if s <= 2 else "S4"
    if p == 6:
        return "S8"
    return "S9"


def done(p, s, i):
    return p == 1 and (s < 5 or (s == 5 and i <= 2))


def minutes(v):
    parts = [int(x) for x in v.split(":")] if re.fullmatch(r"[\d:]+", v) else []
    if len(parts) == 2:
        return parts[0] + parts[1] / 60
    if len(parts) == 3:
        return parts[0] * 60 + parts[1] + parts[2] / 60
    return 0.0


rows = []
for line in SRC.read_text(encoding="utf-8").splitlines():
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", cells[0]) if cells else None
    if not m:
        continue
    p, s, i = (int(x) for x in m.groups())
    if p == 7:  # display | section | title | type | video | repo
        title, typ, video = cells[1], cells[3], cells[4]
    else:
        title, typ, video = cells[1], cells[2], cells[3]
    st = stage(p, s, i)
    if st:
        rows.append((st, cells[0], title, typ, video, minutes(video), done(p, s, i)))

out = ["# Every Ardan chapter, by roadmap stage", "",
       "Generated by `tools/gen_chapters.py`. Do not edit by hand. The tracker is `PROGRESS.md`.",
       "`done` = finished before the roadmap change of 2026-11-15.", ""]
summary = ["| Stage | Items | Left | Video left |", "|---|---|---|---|"]
tot_n = tot_left = 0
tot_min = 0.0
for sid, name, src in STAGES:
    mine = [r for r in rows if r[0] == sid]
    left = [r for r in mine if not r[6]]
    mins = sum(r[5] for r in left)
    tot_n += len(mine)
    tot_left += len(left)
    tot_min += mins
    summary.append(f"| {sid} {name} | {len(mine)} | {len(left)} | {mins / 60:.1f} h |")
    out += [f"## {sid} · {name} ({src})", "", "| # | Title | Type | Video | |", "|---|---|---|---|---|"]
    out += [f"| {r[1]} | {r[2]} | {r[3]} | {r[4]} | {'done' if r[6] else ''} |" for r in mine]
    out.append("")
summary.append(f"| **Total** | **{tot_n}** | **{tot_left}** | **{tot_min / 60:.1f} h** |")
OUT.write_text("\n".join(out[:5] + summary + [""] + out[5:]) + "\n", encoding="utf-8")
print("\n".join(summary))
