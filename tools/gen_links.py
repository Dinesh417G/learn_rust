#!/usr/bin/env python3
"""Build notes/ardan_links.tsv: every item of notes/CHAPTERS.md -> its Ardan player URL.

Source: tools/data/ardan_fp.txt (content ids + a djb2 fingerprint of each slug, read from
the logged-in Ardan dashboard on 2026-11-16). A Thinkific URL is
  https://courses.ardanlabs.com/courses/take/<course>/<kind>/<id>-<slugified name>
and the slugified name equals slugify(title) of our CHAPTERS row, which the fingerprint
proves item by item. Positions are not used: CHAPTERS skips Ardan's text-only chapters,
so from part 2 on the numbers drift.

Usage: python tools/gen_links.py      (prints matched / unmatched)
"""
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FP = ROOT / "tools" / "data" / "ardan_fp.txt"
CHAPTERS = ROOT / "notes" / "CHAPTERS.md"
OUT = ROOT / "notes" / "ardan_links.tsv"
BASE = "https://courses.ardanlabs.com/courses/take"
COURSE = {"0": "ultimate-rust-bundle-guide", "1": "ultimate-rust-crash-course",
          "2": "rust-foundations", "3": "ultimate-rust-foundations-next-steps",
          "4": "ultimate-rust-best-practices", "5": "ultimate-rust-2-intermediate-concepts",
          "6": "rust-as-a-service", "7.1": "rust-foundations-company",
          "7.2": "fearless-concurrency-with-rust", "7.3": "hour-dive-asyc-rust",
          "7.4": "rust-foundations-optimizing-rust-for-embedded-devices",
          "7.5": "debugging-optimizing-rust"}
KIND = {"L": "lessons", "H": "texts", "P": "pdfs", "Q": "quizzes", "S": "surveys"}
TYPE = {"Video": "L", "PDF": "P", "Quiz": "Q", "Text": "H"}
# Webinar videos: their names differ from our titles, so the slug tail is given here
# (read from the same dashboard).
WEBINAR_TAIL = {
    "7.1.1": "introducing-rust-into-your-company-ecosystem",
    "7.2.1": "webinar-with-herbert-aug-27-2024",
    "7.3.1": "webinar-with-herbert-aug-2nd-2023",
    "7.4.1": "rust-foundations-herbert-wolverson",
    "7.5.1": "webinar-with-herbert-wolverson-january-2023",
}


def slugify(s):
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not "̀" <= c <= "ͯ").lower()
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def djb2_36(s):
    h = 5381
    for c in s:
        h = (h * 33 + ord(c)) & 0xFFFFFFFF
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while True:
        h, r = divmod(h, 36)
        out = digits[r] + out
        if not h:
            return out


def main():
    ardan = [l.split() for l in FP.read_text(encoding="utf-8").splitlines()
             if l.strip() and not l.startswith("#")]
    rows = []
    for line in CHAPTERS.read_text(encoding="utf-8").splitlines():
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) >= 4 and re.fullmatch(r"\d+\.\d+\.\d+", c[0]):
            rows.append((c[0], c[1], TYPE.get(c[2], "?")))
    out, missing = [], []
    for item, title, kind in rows:
        p, s, _ = item.split(".")
        part = f"7.{s}" if p == "7" else p
        tail = slugify(title)
        if p == "7":
            hit = [a for a in ardan if a[0] == part and a[2] == "L"]
            tail = WEBINAR_TAIL.get(item)
            if not tail:
                missing.append(f"{item} {title} (webinar: slug tail needed, id {hit[0][1] if hit else '?'})")
                continue
        else:
            hit = [a for a in ardan if a[0] == part and a[3] == djb2_36(tail) and a[2] == kind]
        if len(hit) != 1:
            missing.append(f"{item} {title} ({len(hit)} candidates)")
            continue
        a = hit[0]
        out.append(f"{item}\t{BASE}/{COURSE[part]}/{KIND[a[2]]}/{a[1]}-{tail}")
    OUT.write_text("# item\turl  (generated by tools/gen_links.py; do not edit)\n"
                   + "\n".join(out) + "\n", encoding="utf-8")
    print(f"matched {len(out)} / {len(rows)} -> {OUT.relative_to(ROOT)}")
    for m in missing:
        print("UNMATCHED", m)


if __name__ == "__main__":
    main()
